# Rebuilds chatbots/full-knowledge-file.md from the skill folder.
# Run it after editing SKILL.md or any file in references/, so the
# single-file version used by ChatGPT, Gemini and other chatbots stays in sync.
#
# Windows:        right-click this file > Run with PowerShell
#                 (or: powershell -ExecutionPolicy Bypass -File .\build-single-file.ps1)
# macOS / Linux:  pwsh ./build-single-file.ps1

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$skillDir = Join-Path $root 'steam-sel-lesson-designer'
$outFile = Join-Path (Join-Path $root 'chatbots') 'full-knowledge-file.md'
$utf8 = New-Object System.Text.UTF8Encoding($false)

# Reference files, in the order they are used during a conversation
$references = @(
    'intake-questions.md',
    'handbook-knowledge.md',
    'sdg-lens.md',
    'assessment-and-inclusion.md',
    'research-and-licensing.md',
    'output-templates.md',
    'creating-doodles-music-scripts.md'
)

function Read-Text($path) { return [System.IO.File]::ReadAllText($path, [System.Text.Encoding]::UTF8) }

$skill = Read-Text (Join-Path $skillDir 'SKILL.md')
# Drop the line that points to this single file; it's not needed inside it
$skill = ($skill -split "`r?`n" | Where-Object { $_ -notmatch 'single-file version in the project' }) -join "`n"

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('<!-- Generated by build-single-file.ps1. Do not edit by hand: edit SKILL.md or references/ and run the script again. -->')
[void]$sb.AppendLine()
[void]$sb.AppendLine('> **Single-file version.** This file combines the skill''s main instructions (SKILL.md) and its seven reference files, for chatbots that cannot open separate files. Wherever the text says to read `references/<file>.md`, use the section titled **Reference: <file>.md** further down in this file.')
[void]$sb.AppendLine()
[void]$sb.AppendLine($skill.TrimEnd())

foreach ($ref in $references) {
    $path = Join-Path (Join-Path $skillDir 'references') $ref
    if (-not (Test-Path $path)) { throw "Missing reference file: $path" }
    [void]$sb.AppendLine()
    [void]$sb.AppendLine('---')
    [void]$sb.AppendLine()
    [void]$sb.AppendLine("# Reference: $ref")
    [void]$sb.AppendLine()
    [void]$sb.AppendLine((Read-Text $path).TrimEnd())
}

[System.IO.File]::WriteAllText($outFile, $sb.ToString(), $utf8)
$chars = (Read-Text $outFile).Length
Write-Host "Built $outFile ($chars characters)"
